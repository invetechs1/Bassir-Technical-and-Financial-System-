def _sync_azoom_drive_data():
    """مزامنة بيانات عزوم الرسمية (المستخرجة من وثائق Google Drive) — تعمل بأمان على
    قاعدة قائمة: تضيف الناقص وتكمل الأرقام الفارغة ولا تمس ما أدخله المستخدم."""
    from .database import get_db, now_iso

    # الوثائق: إضافة الجديد وتعبئة الأرقام الرسمية إن كانت فارغة
    existing = {d["name"]: d for d in list_company_docs()}
    for name, issuer, number in SEED_DOCS:
        # مطابقة مرنة (أسماء الوثائق القديمة قبل إضافة الأرقام)
        match = existing.get(name) or next(
            (d for k, d in existing.items() if k.split(" (")[0] == name.split(" (")[0]), None)
        if match:
            if number and not (match.get("number") or "").strip():
                upsert_company_doc({**match, "number": number, "issuer": match.get("issuer") or issuer})
        else:
            upsert_company_doc({"name": name, "issuer": issuer, "number": number})

    # سجل المشاريع الفعلي في المكتبة الفنية (تحديث دائم — هذا مرجع رسمي)
    entries = {e["title"]: e for e in list_library()}
