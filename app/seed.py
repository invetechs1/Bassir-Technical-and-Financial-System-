def _refresh_seed_library():
    """تحديث نصوص المكتبة البذرية للصياغة الحقيقية (مرة واحدة لكل إصدار نصوص)."""
    from .database import get_settings, list_library, update_settings, upsert_library
    if get_settings(company_id=1).get("library_text_version") == LIBRARY_TEXT_VERSION:
        return
    existing = {e["title"]: e for e in list_library()}
    for category, title, body, tags in SEED_LIBRARY:
        if title == "الخبرات والمشاريع المماثلة":
            continue  # يُدار بتحديث سجل الخبرات الفعلي
        cur = existing.get(title)
        if cur:
            upsert_library({**cur, "body": body})
        else:
            upsert_library({"category": category, "title": title, "body": body, "tags": tags})
    update_settings({"library_text_version": LIBRARY_TEXT_VERSION}, company_id=1)


